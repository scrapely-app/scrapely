/**
 * Map an ISO 3166-2 subdivision code (e.g. `US` + `CA`) to the browser's
 * `proxy_state` name (`california`). Returns undefined for unmapped codes.
 */
export function subdivisionToStateName(country: string | undefined, code: string | undefined): string | undefined {
    if (!country || !code) return undefined;
    return SUBDIVISION_NAMES[country.toUpperCase()]?.[code.toUpperCase()];
}
